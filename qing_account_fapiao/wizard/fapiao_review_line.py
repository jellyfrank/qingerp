from odoo import api, fields, models
from odoo.exceptions import AccessError

from .fapiao_review import BUILD_TOKEN

ISSUES = [('registration', 'Pending Registration'), ('confirmation', 'Pending Allocation Confirmation'),
          ('ticket_balance', 'Tax Invoice Not Fully Allocated'), ('bill_balance', 'Bill Not Fully Covered'),
          ('legacy_red', 'Missing Original Blue Invoice'), ('overallocated', 'Overallocated'),
          ('unsupported', 'Negative Amount Requires Review')]


class FapiaoReviewLine(models.TransientModel):
    _name = 'qing.fapiao.review.line'
    _description = 'Tax Invoice Difference'
    _order = 'document_date, id'

    allocated_tax = fields.Monetary(string='Allocated Tax', readonly=True)
    allocated_untaxed = fields.Monetary(string='Allocated Amount', readonly=True)
    amount_tax = fields.Monetary(string='Tax', readonly=True)
    amount_untaxed = fields.Monetary(string='Untaxed Amount', readonly=True)
    color = fields.Selection([('blue', 'Blue'), ('red', 'Red')], string='Color', readonly=True)
    company_id = fields.Many2one(related='review_id.company_id', store=True)
    currency_id = fields.Many2one('res.currency', readonly=True)
    direction = fields.Selection([('in', 'Input'), ('out', 'Output')], string='Direction', readonly=True)
    document_date = fields.Date(string='Document Date', readonly=True)
    document_name = fields.Char(string='Document', readonly=True)
    fapiao_id = fields.Many2one('qing.fapiao', string='Tax Invoice', readonly=True, ondelete='cascade')
    issue = fields.Selection(ISSUES, string='Needs Attention', readonly=True)
    move_id = fields.Many2one('account.move', string='Bill', readonly=True, ondelete='cascade')
    partner_id = fields.Many2one('res.partner', string='Partner', readonly=True)
    pending_count = fields.Integer(string='Unconfirmed Allocations', readonly=True)
    remaining_tax = fields.Monetary(string='Remaining Tax', readonly=True)
    remaining_untaxed = fields.Monetary(string='Remaining Amount', readonly=True)
    review_id = fields.Many2one('qing.fapiao.review', required=True, ondelete='cascade', readonly=True)

    @api.model_create_multi
    def create(self, vals_list):
        if self.env.context.get('fapiao_review_token') is not BUILD_TOKEN:
            raise AccessError(self.env._('Difference rows are generated by the review action.'))
        return super().create(vals_list)

    def write(self, vals):
        raise AccessError(self.env._('Difference rows are read-only. Run the check again to refresh them.'))

    def unlink(self):
        if self.env.context.get('fapiao_review_token') is not BUILD_TOKEN and not self.env.su:
            raise AccessError(self.env._('Difference rows are read-only. Run the check again to refresh them.'))
        return super().unlink()

    def action_open_source(self):
        self.ensure_one()
        self.check_access('read')
        record = (self.fapiao_id or self.move_id).exists()
        record.check_access('read')
        if not record or record.company_id not in self.env.companies:
            raise AccessError(self.env._('The source document is no longer available in the allowed companies.'))
        return {'type': 'ir.actions.act_window', 'name': record.display_name, 'res_model': record._name,
                'res_id': record.id, 'view_mode': 'form', 'target': 'current'}
