from odoo import api, fields, models
from odoo.exceptions import AccessError, UserError

from .common import is_internal


class AccountMove(models.Model):
    _inherit = 'account.move'

    def _reverse_moves(self, default_values_list=None, cancel=False):
        if self.filtered('qing_rental_deposit_id'):
            raise UserError(self.env._('Record a rental deposit refund from the rental order.'))
        return super()._reverse_moves(default_values_list=default_values_list, cancel=cancel)

    qing_rental_deposit_id = fields.Many2one('qing.rental.deposit', readonly=True, copy=False, ondelete='restrict', index=True)

    @api.model_create_multi
    def create(self, vals_list):
        if not is_internal(self.env) and any(vals.get('qing_rental_deposit_id', self.env.context.get('default_qing_rental_deposit_id')) for vals in vals_list):
            raise AccessError(self.env._('Deposit journal entries must be generated by the rental workflow.'))
        return super().create(vals_list)

    def write(self, vals):
        if not is_internal(self.env):
            if 'qing_rental_deposit_id' in vals:
                raise AccessError(self.env._('Deposit accounting links cannot be changed.'))
            if 'state' in vals and vals['state'] != 'posted' and self.filtered(lambda move: move.qing_rental_deposit_id and move.state == 'posted'):
                raise UserError(self.env._('Use a rental deposit refund instead of resetting a posted deposit entry.'))
            if {'line_ids', 'journal_id', 'company_id', 'date', 'partner_id', 'currency_id', 'move_type'}.intersection(vals) and self.filtered(lambda move: move.qing_rental_deposit_id and move.state == 'posted'):
                raise UserError(self.env._('Posted rental deposit entries cannot be changed. Record a refund instead.'))
        return super().write(vals)
